#!/usr/bin/env node
"use strict";
/**
 * Generate `.aipos/CURRENT_TRUTH.md`, the one-page "where are we" file for a cold agent
 * (WO-OPS-20261030-AIPOS-STATUS-ARCHIVE-TRUTH).
 *
 * It is derived only from the work orders (active and archived) and the newest handoff, with no
 * timestamp, so the same repository always produces the same bytes. The file is NOT committed (it is in .gitignore):
 * committing it made every merge that changed a work order turn every other open PR stale. A cold agent generates it
 * on read, so it cannot be stale and cannot be hand-written. `tests/aipos-current-truth.test.js` pins that it stays
 * untracked and that the instructions tell the agent to generate it.
 *
 *   node scripts/generate-aipos-current-truth.js           # write the local, untracked .aipos/CURRENT_TRUTH.md
 *   node scripts/generate-aipos-current-truth.js --stdout  # print it without writing a file
 *   node scripts/generate-aipos-current-truth.js --check   # exit 1 unless the output is non-empty and deterministic
 *
 * The file states what the records CLAIM. A status in a work order is a claim, not proof: verify
 * against GitHub before acting (CLAUDE.md step 2).
 */
const { existsSync, readFileSync, readdirSync, writeFileSync } = require("node:fs");
const { join } = require("node:path");
const { readOrders, classify } = require("./aipos-work-order-index.js");
const { ACTIVE_STATUSES } = require("./lib/aipos-work-order-status.js");
const { listWorkOrderEntries } = require("./lib/aipos-work-order-paths.js");

const OUTPUT = ".aipos/CURRENT_TRUTH.md";
const HANDOFF_DIR = ".aipos/handoffs";
const MAX_ACTIVE_ROWS = 40;

const cell = (value, max = 90) => {
  const text = String(value).replace(/\s+/g, " ").replace(/\|/g, "\\|").trim();
  return text.length > max ? `${text.slice(0, max - 1)}…` : text;
};

// Newest handoff: highest YYYY-MM-DD filename prefix; ties break by file name.
function newestHandoff(root) {
  const dir = join(root, HANDOFF_DIR);
  if (!existsSync(dir)) return null;
  const names = readdirSync(dir).filter((name) => /^\d{4}-\d{2}-\d{2}-.+\.md$/.test(name)).sort();
  if (names.length === 0) return null;
  const name = names[names.length - 1];
  const lines = readFileSync(join(dir, name), "utf8").split(/\r?\n/);
  const title = (lines.find((line) => /^#\s+/.test(line)) || `# ${name}`).replace(/^#\s+/, "");
  const firstParagraph = lines.slice(lines.findIndex((line) => /^#\s+/.test(line)) + 1).join("\n").trim().split(/\n\s*\n/)[0] || "";
  return { path: `${HANDOFF_DIR}/${name}`, title, summary: firstParagraph };
}

function render(root) {
  const entries = listWorkOrderEntries(root);
  const archived = entries.filter((entry) => entry.archived).length;
  const orders = readOrders(root).filter((order) => !entries.find((entry) => entry.name === order.name)?.archived);
  const open = orders.filter((order) => classify(order.status) === "open");
  const active = open.filter((order) => ACTIVE_STATUSES.includes(order.status));
  const byStatus = new Map();
  for (const order of open) byStatus.set(order.status, (byStatus.get(order.status) || 0) + 1);
  const statusRows = [...byStatus].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1)).slice(0, 8);
  const handoff = newestHandoff(root);

  const lines = [
    "# NUSA current truth",
    "",
    "<!-- GENERATED by `node scripts/generate-aipos-current-truth.js`. Do not edit by hand; `tests/aipos-current-truth.test.js` fails when this is stale. -->",
    "",
    "Safety is fixed: `PAPER_ONLY`, `liveAuthority=NONE`, `productionMutationAllowed=false`, `aiAuthority=ZERO_AUTHORITY`.",
    "Everything below is what the repository's records *claim*. Re-verify on GitHub before acting.",
    "",
    "## Newest handoff",
    "",
  ];
  if (handoff) {
    lines.push(`[\`${handoff.path}\`](${handoff.path.replace(/^\.aipos\//, "")}) — ${cell(handoff.title, 160)}`, "", ...handoff.summary.split("\n").map((line) => `> ${line}`), "");
  } else {
    lines.push("No handoff file found.", "");
  }
  lines.push(
    "## Work orders",
    "",
    `${orders.length + archived} total: ${orders.length} in \`.aipos/work-orders/\`, ${archived} closed and merged in \`.aipos/work-orders/archive/\`.`,
    `Of the ${orders.length} active files, ${orders.length - open.length} carry a closed status that has not been archived (merge not proven, or the path is still referenced) and ${open.length} are open or unclassified.`,
    "",
    "Most common statuses among the open files (new orders use only `READY_FOR_REVIEW`, `IN_PROGRESS`, `BLOCKED`, `COMPLETED`, `SUPERSEDED`, `ABANDONED`):",
    "",
    "| Status | Files |",
    "|---|---|",
    ...statusRows.map(([status, count]) => `| ${cell(status, 60)} | ${count} |`),
    "",
    `### In progress or blocked (${active.length})`,
    "",
  );
  if (active.length === 0) {
    lines.push("None recorded.", "");
  } else {
    lines.push("| Work order | Status | Title |", "|---|---|---|");
    for (const order of active.slice(0, MAX_ACTIVE_ROWS)) lines.push(`| \`${cell(order.id, 70)}\` | ${cell(order.status, 20)} | ${cell(order.title)} |`);
    if (active.length > MAX_ACTIVE_ROWS) lines.push("", `…and ${active.length - MAX_ACTIVE_ROWS} more. Full list: \`node scripts/aipos-work-order-index.js\`.`);
    lines.push("");
  }
  lines.push(
    "## Refresh",
    "",
    "- Regenerate: `node scripts/generate-aipos-current-truth.js`. Archive closed, merged orders: `node scripts/aipos-archive-work-orders.js --apply`.",
    "- State: `.aipos/state.yaml` plus `.aipos/state.d/*.yaml`. Open-order index: `node scripts/aipos-work-order-index.js`.",
    "",
  );
  return lines.join("\n");
}

module.exports = { OUTPUT, render, newestHandoff };

if (require.main === module) {
  const root = process.cwd();
  const fresh = render(root);
  if (process.argv.includes("--check")) {
    if (fresh.trim() === "" || fresh !== render(root)) {
      console.error("AIPOS_CURRENT_TRUTH FAIL the generated output is empty or not deterministic");
      process.exit(1);
    }
    console.log("AIPOS_CURRENT_TRUTH PASS (generated on read; the file is not committed)");
  } else if (process.argv.includes("--stdout")) {
    process.stdout.write(fresh);
  } else {
    writeFileSync(join(root, OUTPUT), fresh);
    console.log(`AIPOS_CURRENT_TRUTH wrote ${OUTPUT} (local, untracked)`);
  }
}
